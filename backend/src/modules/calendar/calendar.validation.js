const Joi = require('joi');

const EVENT_TYPES = [
  'milestone',
  'payment',
  'site_visit',
  'report_due',
  'meeting',
  'deadline',
  'stage_advanced',
  'document_approved',
  'document_rejected',
  'variation_approved',
  'project_complete',
];

const linkedEntitySchema = Joi.object({
  type: Joi.string().trim().allow(null, ''),
  id: Joi.string().hex().length(24).allow(null),
});

const createEventSchema = Joi.object({
  projectId: Joi.string().hex().length(24).allow(null),
  deptId: Joi.string().hex().length(24).allow(null),
  title: Joi.string().min(1).max(500).trim().required(),
  eventType: Joi.string().valid(...EVENT_TYPES).required(),
  date: Joi.date().required(),
  endDate: Joi.date().allow(null),
  allDay: Joi.boolean().default(true),
  linkedEntity: linkedEntitySchema.allow(null),
  notes: Joi.string().trim().max(5000).allow(null, ''),
  autoGenerated: Joi.boolean().default(false),
});

const updateEventSchema = Joi.object({
  projectId: Joi.string().hex().length(24).allow(null),
  deptId: Joi.string().hex().length(24).allow(null),
  title: Joi.string().min(1).max(500).trim(),
  eventType: Joi.string().valid(...EVENT_TYPES),
  date: Joi.date(),
  endDate: Joi.date().allow(null),
  allDay: Joi.boolean(),
  linkedEntity: linkedEntitySchema.allow(null),
  notes: Joi.string().trim().max(5000).allow(null, ''),
  autoGenerated: Joi.boolean(),
}).min(1);

const eventListQuerySchema = Joi.object({
  startDate: Joi.date(),
  endDate: Joi.date(),
  projectId: Joi.string().hex().length(24),
  eventType: Joi.string().valid(...EVENT_TYPES),
});

module.exports = {
  createEventSchema,
  updateEventSchema,
  eventListQuerySchema,
};
